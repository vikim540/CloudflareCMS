-- 生成日期：2026-08-03（v1.9.51）
-- 用途：為定時備份配置添加種子數據（默認值）
--
-- 問題背景：
--   備份配置項此前無種子數據，getBackupScheduleConfig() 硬編碼默認 enabled='0'，
--   導致每次打開「數據庫管理」頁面都顯示「未開啟」，用戶以為配置被重置。
--
-- 默認值：
--   - 定時備份：啟用，每週一 03:00 執行
--   - 保留份數：每站 7 份
--   - 備份排除日誌：是（減小備份體積）
--   - 日誌保留：30 天（超過自動清理）
--
-- 冪等語法：INSERT OR IGNORE 不覆蓋已有值（用戶已保存的配置不受影響）
-- ============================================================================

INSERT OR IGNORE INTO ay_config (name, value, type, sorting, description) VALUES
  -- 可編輯配置（sorting 90-96）
  ('backup_schedule_enabled',   '1',      '1', 90, '定時備份開關'),
  ('backup_schedule_frequency', 'weekly', '2', 91, '備份頻率(daily/weekly)'),
  ('backup_schedule_time',      '03:00',  '2', 92, '備份時間(HH:mm)'),
  ('backup_schedule_weekday',   '1',      '2', 93, '備份星期(0=週日,1=週一,2=週二...)'),
  ('backup_schedule_keep',      '7',      '2', 94, '每站保留備份份數'),
  ('backup_exclude_logs',       '1',      '1', 95, '備份排除日誌數據(1=排除,0=包含)'),
  ('log_retention_days',        '30',     '2', 96, '日誌保留天數(0=不自動清理)'),
  -- 只讀配置（sorting 97-98，系統自動更新，不可手動編輯）
  ('backup_last_run',           '',       '2', 97, '上次定時備份執行時間（系統自動更新）'),
  ('log_last_cleanup',          '',       '2', 98, '上次日誌清理執行時間（系統自動更新）');
